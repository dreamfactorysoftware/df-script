<?php

namespace DreamFactory\Core\Script\Engines;

use DreamFactory\Core\Components\PhpExecutable;
use DreamFactory\Core\Exceptions\InternalServerErrorException;
use DreamFactory\Core\Exceptions\ServiceUnavailableException;
use DreamFactory\Core\Script\Components\BaseEngineAdapter;
use \Cache;
use \Log;
use Illuminate\Support\Arr;

/**
 * Abstract class for command executed engines, i.e. those outside of PHP control
 */
abstract class ExecutedEngine extends BaseEngineAdapter
{
    use PhpExecutable;

    /**
     * Seconds a script token stays valid if the script process is never seen to
     * exit (PHP killed mid-run). In the normal path the token is removed the
     * moment the process ends, see releaseScriptToken().
     */
    const SCRIPT_TOKEN_TTL = 300;

    protected $scriptFile = null;

    /**
     * Cache key of the one-time token issued to the running script, or null
     * when no script is running.
     */
    protected $scriptTokenKey = null;

    /**
     * @param array $settings
     *
     * @throws ServiceUnavailableException
     */
    public function __construct(array $settings = [])
    {
        parent::__construct($settings);

        try {
            $this->configure($settings);
        } catch (\Exception $ex) {
            throw new ServiceUnavailableException($ex->getMessage(), $ex->getCode(), $ex->getPrevious());
        }
        if (empty($this->commandName = Arr::get($settings, 'command_name'))) {
            throw new ServiceUnavailableException("Invalid configuration: missing command name.");
        }

        static::startup($settings);
    }

    /**
     * Delete any local script file that
     * was created during execution
     */
    public function __destruct()
    {
        if (!empty($this->scriptFile) && file_exists($this->scriptFile)) {
            @unlink($this->scriptFile);
        }
        $this->releaseScriptToken();
    }

    /**
     * Register the one-time token that lets the script's platform.api calls
     * authenticate as the caller (df-core's AuthCheck middleware looks the
     * token up in the cache). The token only has to live while the script
     * process runs, so executeString() releases it as soon as the process
     * exits; SCRIPT_TOKEN_TTL is just a safety net. Leaving the entry to expire
     * on its own is not an option: the file and database cache drivers never
     * sweep expired entries, so every script run would leave one behind.
     *
     * @param string $token    Random token generated by the engine
     * @param array  $platform Platform access array, see buildPlatformAccess()
     *
     * @return string The token, for embedding in the script
     */
    protected function registerScriptToken($token, array $platform)
    {
        $this->releaseScriptToken();
        $this->scriptTokenKey = 'script-token:' . $token;
        Cache::put($this->scriptTokenKey, [
            'app_id'  => Arr::get($platform, 'session.app.id'),
            'user_id' => Arr::get($platform, 'session.user.id'),
        ], static::SCRIPT_TOKEN_TTL);

        return $token;
    }

    /**
     * Remove the running script's token from the cache. Safe to call when no
     * token is registered.
     */
    protected function releaseScriptToken()
    {
        if (!empty($this->scriptTokenKey)) {
            Cache::forget($this->scriptTokenKey);
            $this->scriptTokenKey = null;
        }
    }

    /**
     * {@inheritdoc}
     */
    public function executeString($script, $identifier, array &$data = [], array $engineArguments = [])
    {
        $data['__tag__'] = 'exposed_event';

        $output = null;
        $return = null;
        try {
            $enrobedScript = $this->enrobeScript($script, $data, static::buildPlatformAccess($identifier));
            $this->scriptFile = $this->getWritablePath($identifier);
            $runnerShell = $this->buildCommand($enrobedScript, $this->scriptFile);

            try {
                $this->execute($runnerShell, $output, $return);
            } catch (\Exception $ex) {
                $message = $ex->getMessage();
                Log::error("Exception executing command based script: $message");

                return null;
            }
        } finally {
            // The script process has exited (or never started), so the token it
            // was issued must not outlive it.
            $this->releaseScriptToken();
        }

        if ($return > 0) {
            // execute() already logs the interpreter's stderr; name the script here rather than
            // repeating the full command line.
            Log::debug("Executed script '$identifier' ({$this->commandName}) exited with code $return");
            throw new InternalServerErrorException('Executed command returned with error code: ' . $return);
        }

        if (null !== $temp = $this->processOutput($output)) {
            $data = $temp;
        }

        return $data;
    }

    /**
     * Override the PhpExecutable trait's execute() so that stderr from the
     * script interpreter is captured and logged on non-zero exit. Without this,
     * missing Python modules, SyntaxErrors, and uncaught runtime exceptions
     * surface only as "Executed command returned with error code: N" with no
     * hint of the underlying cause.
     *
     * Signature and stdout/$return semantics match the trait's version, so
     * existing callers are unaffected.
     */
    public function execute($command, array &$output = null, &$return = null)
    {
        $descriptors = [
            0 => ['pipe', 'r'],
            1 => ['pipe', 'w'],
            2 => ['pipe', 'w'],
        ];
        $process = @proc_open($command, $descriptors, $pipes);
        if (!is_resource($process)) {
            $return = 1;
            $output = [];
            return '';
        }

        fclose($pipes[0]);
        $stdout = stream_get_contents($pipes[1]);
        $stderr = stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);
        $return = proc_close($process);

        $stdout = rtrim((string)$stdout, "\n");
        $output = $stdout === '' ? [] : explode("\n", $stdout);

        if ($return !== 0 && $stderr !== '' && $stderr !== false) {
            Log::error(
                "Script execution failed (exit={$return}). stderr:\n" .
                rtrim($stderr, "\n")
            );
        }

        return $output === [] ? '' : end($output);
    }

    /**
     * Process a single script
     *
     * @param string $path            The path/to/the/script to read and execute
     * @param string $identifier      A string identifying this script
     * @param array  $data            An array of information about the event triggering this script
     * @param array  $engineArguments An array of arguments to pass when executing the string
     *
     * @return mixed
     * @throws InternalServerErrorException
     */
    public function executeScript($path, $identifier, array &$data = [], array $engineArguments = [])
    {
        return $this->executeString(static::loadScript($identifier, $path, true), $identifier, $data, $engineArguments);
    }

    /**
     * @param string $module The name of the module to load
     *
     * @throws \DreamFactory\Core\Exceptions\InternalServerErrorException
     * @return mixed
     */
    public static function loadScriptingModule($module)
    {
        $fullScriptPath = false;

        //  Remove any quotes from this passed in module
        $module = trim(str_replace(["'", '"'], null, $module), ' /');

        //  Check the configured script paths
        if (null === ($script = Arr::get(static::$libraries, $module))) {
            $script = $module;
        }

        foreach (static::$libraryPaths as $key => $path) {
            $checkScriptPath = $path . DIRECTORY_SEPARATOR . $script;

            if (is_file($checkScriptPath) && is_readable($checkScriptPath)) {
                $fullScriptPath = $checkScriptPath;
                break;
            }
        }

        if (!$script || !$fullScriptPath) {
            throw new InternalServerErrorException(
                'The module "' . $module . '" could not be found in any known locations.'
            );
        }

        return file_get_contents($fullScriptPath);
    }

    protected function getWritablePath($identifier)
    {
        $identifier = uniqid($identifier . "_", true);
        $filePath = storage_path('scripting' . DIRECTORY_SEPARATOR . $identifier);
        if ($this->fileExtension) {
            $filePath .= '.' . $this->fileExtension;
        }

        return $filePath;
    }

    /**
     * @param array $output
     *
     * @return null|array
     */
    protected function processOutput(array $output = [])
    {
        $data = null;
        if (is_array($output)) {
            foreach ($output as $item) {
                if (is_string($item)) {
                    if ($this->checkOutputStringForData($item)) {
                        $data = $this->transformOutputStringToData($item);
                    } else {
                        echo $item . PHP_EOL;
                    }
                }
            }
        } elseif (is_string($output)) {
            if ($this->checkOutputStringForData($output)) {
                $data = $this->transformOutputStringToData($output);
            } else {
                echo $output . PHP_EOL;
            }
        }

        return $data;
    }

    protected function checkOutputStringForData($output)
    {
        return ((strlen($output) > 10) && (0 === substr_compare($output, '{"request"', 0, 10)));
    }

    protected function transformOutputStringToData($output)
    {
        return json_decode($output, true);
    }

    /**
     * @param string $script
     * @param array  $data
     * @param array  $platform
     *
     * @return string
     */
    abstract protected function enrobeScript($script, array &$data = [], array $platform = []);
}